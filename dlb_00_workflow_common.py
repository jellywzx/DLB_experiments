KEY = re.compile(r'^\s*(DEF_[A-Za-z0-9_%()]+)\s*=\s*(.*)$',re.I)


class WorkflowError(Exception):
    pass


def _macro_condition(expression:str,state:dict[str,bool],path:Path)->bool:
    """Evaluate the defined(NAME), !, &&, || subset used by define.h."""
    def replace_defined(match:re.Match[str])->str:
        name=match.group(1) or match.group(2)
        return str(bool(state.get(name,False)))

    expression=re.sub(
        r'\bdefined\s*(?:\(\s*(\w+)\s*\)|\s+(\w+))',replace_defined,expression)
    expression=expression.replace('&&',' and ').replace('||',' or ')
    expression=re.sub(r'!(?!=)',' not ',expression)
    if re.sub(r'\b(?:True|False|and|or|not)\b|[()\s]','',expression):
        raise WorkflowError(f'不支持的预处理条件 {path}: {expression.strip()}')
    return bool(eval(expression,{'__builtins__':{}},{}))


def preprocessor_state(path:Path)->dict[str,bool]:
    """Return effective macro state after evaluating define.h conditionals."""
    if not path.is_file():raise WorkflowError(f'源码宏文件不存在: {path}')
    state:dict[str,bool]={}
    # Each frame stores parent-active, whether a branch has matched, and active.
    conditions:list[list[bool]]=[]
    active=True
    for line in path.read_text(encoding='utf-8').splitlines():
        directive=re.match(r'^\s*#(if|ifdef|ifndef|elif|else|endif)\b\s*(.*)',line)
        if directive:
            kind,argument=directive.groups()
            if kind in ('if','ifdef','ifndef'):
                if kind=='if':matched=_macro_condition(argument,state,path)
                else:
                    matched=bool(state.get(argument.strip(),False))
                    if kind=='ifndef':matched=not matched
                conditions.append([active,matched,active and matched])
                active=conditions[-1][2]
            elif kind=='elif':
                if not conditions:raise WorkflowError(f'{path}: 意外的 #elif')
                parent,taken,_=conditions[-1]
                matched=not taken and _macro_condition(argument,state,path)
                conditions[-1]=[parent,taken or matched,parent and matched]
                active=conditions[-1][2]
            elif kind=='else':
                if not conditions:raise WorkflowError(f'{path}: 意外的 #else')
                parent,taken,_=conditions[-1]
                conditions[-1]=[parent,True,parent and not taken]
                active=conditions[-1][2]
            else:
                if not conditions:raise WorkflowError(f'{path}: 意外的 #endif')
                parent,_,_=conditions.pop();active=parent
            continue
        match=re.match(r'^\s*#(define|undef)\s+(\w+)\b',line)
        if active and match:state[match.group(2)]=match.group(1)=='define'
    if conditions:raise WorkflowError(f'{path}: 预处理条件未闭合')
    return state


def clean_value(v: str) -> str:
    """Remove a trailing ! comment outside a Fortran quoted value."""
    quoted = None
    out = []
    i = 0
    while i < len(v):
        c = v[i]
        if c in ("'",'"'):
            if quoted == c and i + 1 < len(v) and v[i+1] == c:
                out.extend((c,c));i+=2;continue
            quoted = None if quoted == c else (c if quoted is None else quoted)
        elif c == '!' and quoted is None:
            break
        out.append(c)
        i+=1
    return ''.join(out).strip()


def assignments(path: Path) -> dict[str,str]:
    if not path.is_file():
        raise WorkflowError(f'缺少 namelist 文件: {path}')
    result: dict[str,str] = {}
    for no,line in enumerate(path.read_text(encoding='utf-8').splitlines(),1):
        m = KEY.match(line)
        if m:
            k=m[1].lower()
            if k in result:
                raise WorkflowError(f'重复 namelist 字段 {k}：{path}:{no}')
            result[k]=clean_value(m[2])
    return result


def get(a: dict[str,str],key: str,default: str|None=None) -> str:
    val=a.get(key.lower(),default)
    if val is None:
        raise WorkflowError(f'缺少 namelist 字段 {key}')
    return val


def string(a:dict[str,str],key:str,default:str|None=None)->str:
    v=get(a,key,default)
    if len(v)>=2 and v[0] in "'\"" and v[-1]==v[0]:
        return v[1:-1].replace(v[0]*2,v[0])
    return v


def boolean(a:dict[str,str],key:str,default:str|None=None)->bool:
    v=get(a,key,default).lower().strip()
    if v in ('.true.','t'):return True
    if v in ('.false.','f'):return False
    raise WorkflowError(f'{key} 不是 Fortran 逻辑值: {v}')


def number(a:dict[str,str],key:str)->int:
    try:return int(get(a,key))
    except ValueError as exc:raise WorkflowError(f'{key} 不是整数') from exc


def path_value(a:dict[str,str],key:str)->Path:
    value=string(a,key)
    if value.lower() in ('','null','none'):
        raise WorkflowError(f'{key} 未配置路径')
    return Path(value).expanduser().resolve()


@dataclass(frozen=True)
class Run:
    label:str
    case:str
    nml:Path
    conf:dict[str,str]
    dam:int
    levee:bool
    bif:bool
    case_root:Path
    spec:dict[str,Any]
    @property
    def case_dir(self)->Path:return self.case_root/self.case
    @property
    def restart(self)->Path:return self.case_dir/'restart'
    @property
    def history(self)->Path:return self.case_dir/'history'


@dataclass(frozen=True)
class Study:
    nml_dir:Path
    manifest:dict[str,Any]
    spinup:Run
    dam_init:Run|None
    experiments:tuple[Run,...]
    eval_start_year:int
    eval_end_year:int
    @property
    def by_label(self)->dict[str,Run]:return {x.label:x for x in self.experiments}
    @property
    def case_root(self)->Path:return self.spinup.case_root


def load_study(nml_dir:Path, allow_draft:bool=False, validate_schedule:bool=True)->Study:
    nml_dir=nml_dir.expanduser().resolve()
    try:
        manifest=json.loads((nml_dir/'run_manifest.json').read_text(encoding='utf-8'))
        with (nml_dir/'experiments.csv').open(newline='',encoding='utf-8') as f:
            rows=list(csv.DictReader(f))
    except (FileNotFoundError, ValueError, OSError) as exc:
        raise WorkflowError(f'无法读取 manifest/experiments.csv: {exc}') from exc
    if manifest.get('draft') and not allow_draft:
        raise WorkflowError('配置由 --draft 生成，不允许进入运行工作流；先严格重新生成')
    regions={r.get('region') for r in rows}
    if len(regions)!=1:
        raise WorkflowError('运行工具一次只接受一个区域的配置目录')
    region=next(iter(regions))
    if [r.get('experiment') for r in rows] != list(EXPERIMENTS):
        raise WorkflowError('experiments.csv 不等于项目固定的 E0–E7 全因子顺序')

    def one(label:str,filename:str,expected_case:str|None,sw:tuple[int,bool,bool],
            spec:dict[str,Any]|None=None)->Run:
        nml=nml_dir/filename
        conf=assignments(nml)
        case=string(conf,'DEF_CASE_NAME')
        if expected_case and case!=expected_case:raise WorkflowError(f'{label}: CSV case_name 与 namelist 不符')
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_-]{0,150}',case):
            raise WorkflowError(f'{label}: 非安全的 case 名 {case!r}')
        actual=(number(conf,'DEF_Reservoir_Method'),boolean(conf,'DEF_USE_LEVEE'),boolean(conf,'DEF_USE_BIFURCATION'))
        if actual!=sw:raise WorkflowError(f'{label}: 三过程开关错误 {actual}，预期 {sw}')
        root=path_value(conf,'DEF_dir_output')
        return Run(label,case,nml,conf,*sw,root,spec or {})

    runs=manifest.get('runs',{}) if manifest.get('schema_version')==2 else {}
    exp_specs=runs.get('experiments',{}).get(region,[]) if runs else []
    specs_by_label={x.get('label'):x for x in exp_specs}
    exp=tuple(one(r['experiment'],r['nml_file'],r['case_name'],SWITCHES[r['experiment']],
                  specs_by_label.get(r['experiment'])) for r in rows)

    def find_case_nml(fragment:str)->tuple[str,str]:
        hits=[]
        for path in nml_dir.glob('*.nml'):
            try: case=string(assignments(path),'DEF_CASE_NAME')
            except WorkflowError: continue
            if fragment.lower() in case.lower():hits.append((path.name,case))
        if len(hits)!=1:
            raise WorkflowError(f'无法唯一定位 {fragment} namelist，找到 {len(hits)} 个')
        return hits[0]

    spin_spec=runs.get('spinup',{}).get(region) if runs else None
    if spin_spec:
        spin_file,spin_case=spin_spec['nml_file'],spin_spec['case']
    else:
        spin_file,spin_case=find_case_nml('_spinup_')
    spin=one('SPINUP',spin_file,spin_case,(0,False,False),spin_spec)

    dam_spec=runs.get('dam_init',{}).get(region) if runs else None
    dam_init=None
    if dam_spec:
        dam_init=one('D_INIT',dam_spec['nml_file'],dam_spec['case'],(1,False,False),dam_spec)
    elif list(nml_dir.glob('*_D_INIT_*.nml')):
        dam_file,dam_case=find_case_nml('_D_INIT_')
        dam_init=one('D_INIT',dam_file,dam_case,(1,False,False))
    all_runs=(spin,*(([dam_init]) if dam_init else []),*exp)
    if any(x.case_root!=spin.case_root for x in all_runs):
        raise WorkflowError('各组 DEF_dir_output 不一致')
    if len({x.case for x in all_runs})!=len(all_runs):
        raise WorkflowError('不同实验的 DEF_CASE_NAME 重复')
    evaluation=manifest.get('evaluation',{})
    eval_start=int(evaluation.get('start_year',2001))
    eval_end=int(evaluation.get('end_year',2005))
    if not 2000<=eval_start<=eval_end<=2005:
        raise WorkflowError('manifest evaluation 年份不在 2000–2005 内')
    study=Study(nml_dir,manifest,spin,dam_init,exp,eval_start,eval_end)
    if validate_schedule:validate_study_schedule(study)
    return study


def validate_study_schedule(study:Study,targets:tuple[Run,...]|None=None)->None:
    if (number(study.spinup.conf,'DEF_simulation_time%start_year'),
        number(study.spinup.conf,'DEF_simulation_time%end_year'))!=(1996,1999):
        raise WorkflowError('共享 Spinup 年份应为 1996–1999')
    selected=study.experiments if targets is None else targets
    for run in selected:
        if (number(run.conf,'DEF_simulation_time%start_year'),
            number(run.conf,'DEF_simulation_time%end_year'))!=(2000,2005):
            raise WorkflowError(f'{run.label} 运行年限应为 2000–2005')
        if boolean(run.conf,'DEF_GridRiverLake_FloodFeedback'):
            raise WorkflowError(f'{run.label} 开启了洪泛—陆面反馈，违反研究的单向耦合设计')
    if study.dam_init and any(run.dam for run in selected):
        dam_start=number(study.dam_init.conf,'DEF_simulation_time%start_year')
        dam_end=number(study.dam_init.conf,'DEF_simulation_time%end_year')
        if not 1996<=dam_start<=2000 or dam_end!=2000:
            raise WorkflowError(
                f'D_INIT 年份应满足起始年 1996–2000 且结束年为 2000，'
                f'实际为 {dam_start}–{dam_end}')


def select(study:Study,only:str)->tuple[Run,...]:
    if only.lower()=='all':return study.experiments
    names=[x.strip() for x in only.split(',') if x.strip()]
    if not names or len(set(names))!=len(names) or any(x not in study.by_label for x in names):
        raise WorkflowError('--only 必须为 all 或逗号分隔的 E0_CTL,...,E7_ALL')
    return tuple(study.by_label[x] for x in names)


def stamp(year:int)->str:
    return f'{year:04d}-001-00000'


def timefiles(run:Run,year:int)->list[Path]:
    t=run.restart/stamp(year)
    return sorted(t.glob('*.nc')) if t.is_dir() else []


def constfiles(run:Run)->list[Path]:
    t=run.restart/'const'
    return sorted(t.glob('*.nc')) if t.is_dir() else []


def validate_restart_filenames(files:list[Path],run:Run,year:int|None)->list[str]:
    errors=[]
    if not files:return [f'{run.case} 未找到 {stamp(year) if year is not None else "const"} 的任何 .nc 文件']
    cases=[p.name for p in files if not p.is_symlink() and p.stat().st_size>0]
    if len(cases)!=len(files):errors.append('存在软链接或空文件，不允许作为可信的 restart 源')
    for p in files:
        if not p.name.startswith(f'{run.case}_restart_'):
            errors.append(f'文件名前缀不匹配: {p.name}')
        if year is not None and stamp(year) not in p.name:
            errors.append(f'时间戳不匹配: {p.name}')
    if year is None:
        need=('_restart_const_lc','_restart_pft_const_lc')
    else:
        need=(f'_restart_{stamp(year)}_lc',f'_restart_gridriver_{stamp(year)}_lc',
              f'_restart_pft_{stamp(year)}_lc')
    for part in need:
        if not any(part in name for name in cases):errors.append(f'缺少关键 restart 文件类型 {part}')
    return errors


def probe_netcdf(path:Path, names:tuple[str,...]=())->tuple[set[str],dict[str,Any]]:
    """Only metadata and scalar fields. Requires netCDF4 (best) or SciPy for classic NetCDF3."""
    try:
        from netCDF4 import Dataset
    except ImportError:
        Dataset=None
    if Dataset is not None:
        try:
            with Dataset(str(path),'r') as ds:
                keys=set(ds.variables)
                vals={n:ds.variables[n][()].item() if hasattr(ds.variables[n][()],'item') else ds.variables[n][()]
                      for n in names if n in keys}
                return keys,vals
        except Exception as exc:
            raise WorkflowError(f'无法读取 NetCDF 元数据 {path}: {exc}') from exc
    try:
        from scipy.io import netcdf_file
    except ImportError as exc:
        raise WorkflowError('检查 NetCDF 必须安装 netCDF4（推荐；SciPy 仅支持 NetCDF3）') from exc
    try:
        with netcdf_file(str(path),'r',mmap=False) as ds:
            keys=set(ds.variables)
            vals={n:ds.variables[n].data.reshape(-1)[0].item() for n in names if n in keys}
            return keys,vals
    except Exception as exc:
        raise WorkflowError(f'无法读取 {path}；若为 NetCDF4 请安装 netCDF4: {exc}') from exc


def gridriver_file(files:list[Path],run:Run,year:int)->Path:
    part=f'{run.case}_restart_gridriver_{stamp(year)}_lc'
    hits=[p for p in files if p.name.startswith(part)]
    if len(hits)!=1:raise WorkflowError(f'期望恰好 1 个 gridriver restart，实际 {len(hits)}: {part}')
    return hits[0]


def gridriver_integrity(file:Path,dam:int,levee:bool,bif:bool)->tuple[list[str],list[str]]:
    """Validate transaction metadata & essential feature-dependent states; never mutate file."""
    errors=[];notes=[]
    keys,val=probe_netcdf(file,('gridriver_restart_schema','gridriver_restart_complete',
                                 'gridriver_restart_feature_levee','gridriver_restart_feature_bifurcation'))
    schema=val.get('gridriver_restart_schema')
    if schema is None:
        errors.append('legacy GridRiver restart 无事务元数据，需人工验证后才能跨过程分发')
    elif int(schema) not in (1,2):
        errors.append(f'不支持的 GridRiverLake restart schema: {schema}')
    if val.get('gridriver_restart_complete')!=1:
        errors.append('gridriver_restart_complete != 1，可能是未完成写入')
    for v in ('wdsrf_ucat','veloc_riv','acctime_rnof','acc_rnof_uc','volwater_ucat'):
        if v not in keys:errors.append(f'缺少基础河道状态: {v}')
    if dam and 'volresv' not in keys:
        errors.append('水库开启但源 restart 缺少 volresv（CTL 无水库时通常不写该变量）；不可直接分发')
    if dam and schema==2 and 'gridriver_reservoir_identity' not in keys:
        errors.append('水库开启但源 restart 缺少 gridriver_reservoir_identity；schema-v2 必需')
    if schema==2:
        for v in ('gridriver_restart_feature_bifurcation','gridriver_restart_feature_levee'):
            if v not in keys:errors.append(f'缺少 schema-v2 特征 manifest: {v}')
        if 'gridriver_ucatch_identity' not in keys:
            errors.append('缺少 gridriver_ucatch_identity')
        if bool(val.get('gridriver_restart_feature_levee',0))!=levee:
            notes.append('Levee 开关与源 restart 不同：依赖源码的跨特征初始化，需短测验证')
        if bool(val.get('gridriver_restart_feature_bifurcation',0))!=bif:
            notes.append('BIF 开关与源 restart 不同：依赖源码的跨特征初始化，需短测验证')
    return errors,notes


def month_files(run:Run,start_year:int=2001,end_year:int=2005)->tuple[int,int,list[str]]:
    """Route-history monthly presence check (not full time-variable integrity)."""
    missing=[];count=0
    for year in range(start_year,end_year+1):
        for month in range(1,13):
            name=f'{run.case}_hist_unitcat_{year:04d}-{month:02d}.nc'
            if (run.history/name).is_file() and (run.history/name).stat().st_size>0:count+=1
            else:missing.append(name)
    expected=(end_year-start_year+1)*12
    return count,expected,missing


def error_exit(exc:Exception)->int:
    import sys
    print(f'ERROR: {exc}',file=sys.stderr)
    return 2
